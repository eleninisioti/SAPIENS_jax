"""Actor-critic agents that share trajectories over the social network, corrected with V-trace.

Each update, every agent collects ROLLOUT_LEN steps in each of its NUM_ENVS environments.
With probability P_SHARE it sends SHARE_BATCH of these trajectories (a different random subset
for each neighbour) to its current neighbours. It then takes one gradient step on its own and the
received trajectories. Received trajectories were generated by another policy, so returns and
advantages are computed with V-trace (Espeholt et al., 2018), as in IMPALA.

With TOPOLOGY=centralized all agents act with one network that learns from all trajectories:
the synchronous IMPALA / A2C setting of standard distributed RL.
"""
import jax
import jax.numpy as jnp
import optax

from sapiens import topology
from sapiens.common import (ActorCritic, conv_shape, count_unique, disagreement, hash_transitions, hash_weights,
                            init_params, make_evaluate, pooled_grads)


def steps_per_update(cfg):
    return cfg["ROLLOUT_LEN"] * cfg["NUM_ENVS"]


def vtrace(values, bootstrap, rewards, dones, rhos, gamma, clip_rho, clip_c):
    """V-trace targets and policy-gradient advantages for one time-major trajectory."""
    discounts = gamma * (1.0 - dones)
    rho_c = jnp.minimum(rhos, clip_rho)
    cs = jnp.minimum(rhos, clip_c)
    v_tp1 = jnp.concatenate([values[1:], bootstrap[None]])
    deltas = rho_c * (rewards + discounts * v_tp1 - values)

    def backward(acc, x):
        delta, discount, c = x
        acc = delta + discount * c * acc
        return acc, acc

    _, corrections = jax.lax.scan(backward, jnp.zeros(()), (deltas, discounts, cs), reverse=True)
    vs = values + corrections
    vs_tp1 = jnp.concatenate([vs[1:], bootstrap[None]])
    advantages = rho_c * (rewards + discounts * vs_tp1 - values)
    return jax.lax.stop_gradient(vs), jax.lax.stop_gradient(advantages)


def make_train(cfg, env):
    n, n_envs, horizon = cfg["NUM_AGENTS"], cfg["NUM_ENVS"], cfg["ROLLOUT_LEN"]
    update_steps = steps_per_update(cfg)
    n_logs = cfg["TOTAL_STEPS"] // cfg["LOG_INTERVAL"]
    updates_per_log = cfg["LOG_INTERVAL"] // update_steps
    share_batch = min(cfg["SHARE_BATCH"], n_envs)
    centralized = cfg["TOPOLOGY"] == "centralized"
    sharing = cfg["TOPOLOGY"] not in ("independent", "centralized") and n > 1
    n_received = n * share_batch if sharing else 0
    network = ActorCritic(env.num_actions, tuple(cfg["HIDDEN"]), conv_shape(cfg, env))
    tx = optax.chain(optax.clip_by_global_norm(cfg["MAX_GRAD_NORM"]), optax.adam(cfg["LR"], eps=1e-5))

    def eval_act(p, obs, key):
        logits, _ = network.apply(p, obs)
        return logits.argmax() if cfg["EVAL_GREEDY"] else jax.random.categorical(key, logits)

    def group_disagreement(params, obs):
        probe = obs.reshape(-1, env.obs_dim)  # current observations of all agents
        values = jax.vmap(lambda p: network.apply(p, probe)[0])(params)
        return disagreement(values)

    def adapt(s, t):
        returns = jnp.where(s["adapt_count"] > 0, s["adapt_sum"] / jnp.maximum(s["adapt_count"], 1), -jnp.inf)
        topo = topology.adapt(s["topo"], t, cfg, group_disagreement(s["params"], s["obs"]), returns)
        return dict(s, topo=topo, adapt_sum=jnp.zeros((n,)), adapt_count=jnp.zeros((n,)))

    def maybe_adapt(s, t):
        if cfg["TOPOLOGY"] not in topology.ADAPTIVE:
            return s
        return jax.lax.cond(t % cfg["ADAPT_INTERVAL"] < update_steps, lambda s: adapt(s, t), lambda s: s, s)

    evaluate = make_evaluate(env, eval_act, cfg["EVAL_STEPS"] or env.max_steps, cfg["EVAL_EPISODES"])
    vreset = jax.vmap(jax.vmap(env.reset, in_axes=(0, None)), in_axes=(0, None))
    vstep = jax.vmap(jax.vmap(env.step, in_axes=(0, 0, 0, None)), in_axes=(0, 0, 0, None))

    def trajectory_loss(params, traj):
        """traj: obs (T+1, D), action / reward / done / logp (T,)."""
        logits, values = network.apply(params, traj["obs"])
        logp_all = jax.nn.log_softmax(logits[:-1])
        logp = jnp.take_along_axis(logp_all, traj["action"][:, None], -1)[:, 0]
        rhos = jnp.exp(jax.lax.stop_gradient(logp) - traj["logp"])
        vs, adv = vtrace(values[:-1], values[-1], traj["reward"], traj["done"], rhos,
                         cfg["GAMMA"], cfg["CLIP_RHO"], cfg["CLIP_C"])
        pg_loss = -(logp * adv).mean()
        v_loss = 0.5 * ((vs - values[:-1]) ** 2).mean()
        entropy = -(jnp.exp(logp_all) * logp_all).sum(-1).mean()
        return pg_loss + cfg["VF_COEF"] * v_loss - cfg["ENT_COEF"] * entropy

    def batch_loss(params, trajs, weights):
        losses = jax.vmap(trajectory_loss, in_axes=(None, 0))(params, trajs)
        return (losses * weights).sum() / jnp.maximum(weights.sum(), 1.0)

    def train(rng, task_key, adj0):
        env_params = env.params(task_key)
        rng, k_net, k_env, k_hash = jax.random.split(rng, 4)
        params = init_params(network, k_net, n, env.obs_dim, shared=centralized)
        obs, env_state = vreset(jax.random.split(k_env, n * n_envs).reshape(n, n_envs, -1), env_params)
        w_obs, w_act = hash_weights(k_hash, env.obs_dim)
        batch_size = (n_envs + n_received) * horizon

        zeros = jnp.zeros((n,), jnp.float32)
        state = dict(
            params=params, opt=jax.vmap(tx.init)(params), env_state=env_state, obs=obs,
            topo=topology.init_state(cfg, adj0), ep_return=jnp.zeros((n, n_envs)),
            ret_sum=zeros, ret_count=zeros, loss_sum=zeros, loss_count=zeros, received=zeros,
            batch_hash=jnp.zeros((n, batch_size), jnp.uint32), batch_valid=jnp.zeros((n, batch_size), bool),
            adapt_sum=zeros, adapt_count=zeros, rng=rng,
        )

        def env_step(s, t):
            rng, k_act, k_env, k_topo = jax.random.split(s["rng"], 4)
            logits, _ = jax.vmap(jax.vmap(network.apply, in_axes=(None, 0)))(s["params"], s["obs"])
            action = jax.random.categorical(k_act, logits)
            logp = jnp.take_along_axis(jax.nn.log_softmax(logits), action[..., None], -1)[..., 0]
            next_obs, env_state, reward, done = vstep(
                jax.random.split(k_env, n * n_envs).reshape(n, n_envs, -1), s["env_state"], action, env_params)
            ep_return = s["ep_return"] + reward
            step = dict(obs=s["obs"], action=action, reward=reward, done=done.astype(jnp.float32), logp=logp)
            s = dict(
                s, env_state=env_state, obs=next_obs, rng=rng,
                ret_sum=s["ret_sum"] + jnp.where(done, ep_return, 0.0).sum(-1),
                ret_count=s["ret_count"] + done.sum(-1),
                adapt_sum=s["adapt_sum"] + jnp.where(done, ep_return, 0.0).sum(-1),
                adapt_count=s["adapt_count"] + done.sum(-1),
                ep_return=jnp.where(done, 0.0, ep_return),
                topo=topology.step(s["topo"], k_topo, t + n_envs, cfg, dt=n_envs),
            )
            return s, step

        def update_step(s, t0):
            s, steps = jax.lax.scan(env_step, s, t0 + jnp.arange(horizon) * n_envs)
            # (T, N, E, ...) -> (N, E, T, ...), with the bootstrap observation appended to obs
            trajs = jax.tree.map(lambda x: jnp.moveaxis(x, 0, 2), steps)
            trajs["obs"] = jnp.concatenate([trajs["obs"], s["obs"][:, :, None]], axis=2)
            weights = jnp.ones((n, n_envs))
            received = s["received"]
            rng, k_share, k_pick = jax.random.split(s["rng"], 3)

            if sharing:
                active = jax.random.uniform(k_share, (n,)) < cfg["P_SHARE"]
                send = s["topo"].adj & active[:, None]                         # (sender, receiver)
                # sender i sends a random subset of its trajectories to each receiver j: (i, j, L)
                picks = jax.vmap(lambda k: jax.random.permutation(k, n_envs)[:share_batch])(
                    jax.random.split(k_pick, n * n)).reshape(n, n, share_batch)
                sent = jax.tree.map(lambda x: jax.vmap(lambda xi, pi: xi[pi])(x, picks), trajs)  # (i, j, L, ...)
                incoming = jax.tree.map(lambda x: jnp.swapaxes(x, 0, 1).reshape(n, n * share_batch, *x.shape[3:]), sent)
                in_mask = jnp.repeat(send.T, share_batch, axis=1).astype(jnp.float32)  # (receiver, sender * L)
                trajs = jax.tree.map(lambda a, b: jnp.concatenate([a, b], axis=1), trajs, incoming)
                weights = jnp.concatenate([weights, in_mask], axis=1)
                received = received + in_mask.sum(1)

            if centralized:
                loss, grads = pooled_grads(batch_loss, s["params"], trajs, weights)
            else:
                loss, grads = jax.vmap(jax.value_and_grad(batch_loss))(s["params"], trajs, weights)
            updates, opt = jax.vmap(tx.update)(grads, s["opt"], s["params"])

            hashes = hash_transitions(trajs["obs"][:, :, :-1], trajs["action"], w_obs, w_act).reshape(n, -1)
            valid = jnp.repeat(weights > 0, horizon, axis=1)
            s = dict(s, params=optax.apply_updates(s["params"], updates), opt=opt, rng=rng, received=received,
                     loss_sum=s["loss_sum"] + loss, loss_count=s["loss_count"] + 1,
                     batch_hash=hashes, batch_valid=valid)
            return maybe_adapt(s, t0 + update_steps), None

        def log_step(s, t0):
            s, _ = jax.lax.scan(update_step, s, t0 + jnp.arange(updates_per_log) * update_steps)
            rng, k_eval = jax.random.split(s["rng"])
            eval_return, traj_hash, achievements, eval_length = evaluate(s["params"], k_eval, env_params)
            metrics = dict(
                step=t0 + cfg["LOG_INTERVAL"],
                train_return=s["ret_sum"] / jnp.maximum(s["ret_count"], 1),
                episodes=s["ret_count"],
                loss=s["loss_sum"] / jnp.maximum(s["loss_count"], 1),
                eval_return=eval_return,
                eval_length=eval_length,
                traj_hash=traj_hash,
                achievements=achievements,
                # diversity of the last learning batch (own and received trajectories)
                diversity=jax.vmap(count_unique)(s["batch_hash"], s["batch_valid"]),
                group_diversity=count_unique(s["batch_hash"].reshape(-1), s["batch_valid"].reshape(-1)),
                received=s["received"],
                disagreement=group_disagreement(s["params"], s["obs"]),
                degree=s["topo"].adj.sum(1),
                group=s["topo"].group,
            )
            s = dict(s, rng=rng, ret_sum=zeros, ret_count=zeros, loss_sum=zeros, loss_count=zeros, received=zeros)
            return s, metrics

        state, metrics = jax.lax.scan(log_step, state, jnp.arange(n_logs) * cfg["LOG_INTERVAL"])
        return metrics, state["params"]

    return train
