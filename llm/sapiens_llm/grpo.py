"""GRPO with shared completions: advantages, importance weights, per-token log-probabilities, loss.

A learner's batch holds its own completions (generated by its current policy, so on-policy) and
completions received from neighbours (generated by their policies). For each prompt, the own and
received completions form one GRPO group: advantages are rewards standardised within the group.
Received tokens are weighted by the truncated importance ratio min(pi_receiver / pi_sender, CLIP),
detached, as V-trace does for off-policy actors. One optimizer step per iteration, so no PPO clipping
is needed for the own completions. The loss is averaged over all completion tokens (as in DAPO).
"""
import numpy as np
import torch


def group_advantages(rewards, prompt_index, eps=1e-4):
    rewards, prompt_index = np.asarray(rewards, np.float32), np.asarray(prompt_index)
    adv = np.zeros_like(rewards)
    for p in np.unique(prompt_index):
        m = prompt_index == p
        adv[m] = (rewards[m] - rewards[m].mean()) / (rewards[m].std() + eps)
    return adv


def collate(samples, pad_id):
    """samples: dicts with prompt_ids, completion_ids (lists). Right-padded input_ids, attention
    mask, and a completion mask aligned with the next-token targets (shape B x L-1)."""
    seqs = [s["prompt_ids"] + s["completion_ids"] for s in samples]
    length = max(map(len, seqs))
    input_ids = torch.full((len(seqs), length), pad_id, dtype=torch.long)
    attention = torch.zeros((len(seqs), length), dtype=torch.long)
    completion = torch.zeros((len(seqs), length - 1), dtype=torch.float32)
    for b, (s, seq) in enumerate(zip(samples, seqs)):
        input_ids[b, :len(seq)] = torch.tensor(seq)
        attention[b, :len(seq)] = 1
        start = len(s["prompt_ids"]) - 1   # target index of the first completion token
        completion[b, start:start + len(s["completion_ids"])] = 1.0
    return input_ids, attention, completion


def token_logprobs(model, input_ids, attention):
    """log pi(token_t+1 | tokens_<=t) for every position, shape B x L-1, without materialising a
    float32 copy of the full logits tensor."""
    logits = model(input_ids=input_ids, attention_mask=attention).logits[:, :-1]
    targets = input_ids[:, 1:]
    out = []
    for row_logits, row_targets in zip(logits, targets):   # one sequence at a time keeps memory flat
        row_logits = row_logits.float()
        out.append(row_logits.gather(-1, row_targets[:, None])[:, 0] - torch.logsumexp(row_logits, -1))
    return torch.stack(out)


def policy_loss(logprobs, behaviour_logprobs, advantages, completion_mask, received, clip):
    """Sum over tokens of -w * A * log pi (normalise by the token count outside).

    received: (B,) bool; for those rows w = min(exp(log pi - log mu), clip), detached; else w = 1.
    """
    ratio = torch.exp(logprobs.detach() - behaviour_logprobs).clamp(max=clip)
    weights = torch.where(received[:, None], ratio, torch.ones_like(ratio))
    return -(weights * advantages[:, None] * logprobs * completion_mask).sum()
